/// `FlowBuilder::generate` over owned, `Arc`-shared data: see `tests/fill.rs`'s
/// identical shape, over `generate` instead.
#[test]
fn flow_builder_generate_locks_and_runs_over_owned_data() {
    let data = over_owned_data(|taskflow, data| {
        taskflow.generate(
            data,
            || 9,
            GuidedPartitioner::<DefaultClosureWrapper>::default(),
        );
    });

    assert_all(&data, 9);
}

/// `FlowBuilder::generate_n` over owned, `Arc`-shared data.
#[test]
fn flow_builder_generate_n_locks_and_runs_over_owned_data() {
    let data = over_owned_data(|taskflow, data| {
        taskflow.generate_n(
            data,
            250,
            || 9,
            GuidedPartitioner::<DefaultClosureWrapper>::default(),
        );
    });

    assert_filled_to(&data, 250, 9, 0);
}

/// The closure wrapper runs once per worker task over that worker's whole
/// share. Upstream's `test_generate.cpp` carries no `ClosureWrapper.generate.*`
/// case of its own; see `tests/fill.rs`'s identical note.
#[test]
fn closure_wrapper_runs_once_per_worker() {
    wrapper_runs_once_per_worker(|runtime, data, part| {
        runtime.generate(data, || 1, part);
        assert!(data.iter().all(|&v| v == 1));
    });
}
