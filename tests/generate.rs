/// Upstream's `ParallelGenerateStateful.4`: a borrowed slice computed by a
/// runtime task from state an earlier task set up -- see `tests/fill.rs`'s
/// identical shape.
#[test]
fn parallel_generate_stateful() {
    let backing = from_a_setup_task(4, |runtime, data| {
        runtime.generate(
            data,
            || 12,
            GuidedPartitioner::<DefaultClosureWrapper>::default(),
        );
    });

    assert_all(&backing, 12);
}

/// Upstream's `ParallelGenerateStatefulMixed.4`: see `tests/fill.rs`'s
/// identical shape.
#[test]
fn parallel_generate_stateful_mixed() {
    let backing = bounded_by_a_setup_task(4, |runtime, data| {
        runtime.generate(
            data,
            || 12,
            GuidedPartitioner::<DefaultClosureWrapper>::default(),
        );
    });

    assert_all(&backing, 12);
}

/// Upstream's `ParallelGenerateNStateful.1`.
#[test]
fn parallel_generate_n_stateful() {
    let backing = from_a_setup_task(4, |runtime, data| {
        runtime.generate_n(
            data,
            5000,
            || 12,
            GuidedPartitioner::<DefaultClosureWrapper>::default(),
        );
    });

    assert_filled_to(&backing, 5000, 12, 0);
}

