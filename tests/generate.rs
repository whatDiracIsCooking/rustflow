/// Upstream's `generate_n_partioners<P>(W, N, part)`: `generate_n` touches
/// only the first `N / 2` elements, leaving the rest at their initial value.
fn parallel_generate_n<P>(workers: usize, make: impl Fn() -> P)
where
    P: SlicePartitioner + Send + 'static,
{
    over_lengths(workers, make, |runtime, data, part| {
        let n = data.len();
        let count = n / 2;
        runtime.generate_n(data, count, || 12, part);
        assert!(data[..count].iter().all(|&v| v == 12), "n={n}");
        assert!(data[count..].iter().all(|&v| v == 0), "n={n}");
    });
}

fn parallel_generate_n_static(workers: usize) {
    parallel_generate_n(workers, StaticPartitioner::<DefaultClosureWrapper>::default);
}

fn parallel_generate_n_dynamic(workers: usize) {
    parallel_generate_n(
        workers,
        DynamicPartitioner::<DefaultClosureWrapper>::default,
    );
}

fn parallel_generate_n_random(workers: usize) {
    parallel_generate_n(workers, RandomPartitioner::<DefaultClosureWrapper>::default);
}

fn parallel_generate_n_default(workers: usize) {
    parallel_generate_n(workers, DefaultPartitioner::default);
}

