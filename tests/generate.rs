//! Translated from `unittests/test_generate.cpp` (Taskflow v4.1.0):
//! `ParallelGenerate.*`, `ParallelGenerateN.*`, `ParallelGenerateStateful.4`,
//! `ParallelGenerateStatefulMixed.4` and `ParallelGenerateNStateful.1`.
//!
//! Every case here uses a stateless generator, matching upstream's own
//! `[val](){ return val; }` -- the one shape
//! `src/algorithm/generate.rs`'s `# Design` section's departure from
//! upstream (one shared, evolving generator behind a `Mutex`, not a copy per
//! worker) cannot be told apart from upstream's own semantics for. That
//! module's own `generate_calls_a_single_shared_generator_once_per_element`
//! unit test is where a stateful generator is exercised.
//!
//! Two adaptations, both forced by the port rather than chosen, mirroring
//! `tests/fill.rs`'s own:
//!
//! - **No `ParallelGenerateAsync`/`ParallelGenerateNAsync`.** No
//!   `make_generate_task` free function survives the port -- see
//!   `tests/fill.rs`'s own docs for why, and `src/algorithm/generate.rs`'s.
//! - **One sweep per worker count, not upstream's fixed four**, over `i64`
//!   alone rather than `int` and `long double` both: the element type does
//!   not interact with the partitioning logic this port is checking.

use std::sync::atomic::{AtomicUsize, Ordering};
use std::sync::{Arc, Mutex};

use rustflow::algorithm::SlicePartitioner;
use rustflow::algorithm::partitioner::{
    DefaultClosureWrapper, DefaultPartitioner, DynamicPartitioner, GuidedPartitioner,
    RandomPartitioner, StaticPartitioner,
};
use rustflow::prelude::*;
use rustflow::{Executor, Runtime};

#[macro_use]
mod common;

/// The length side of the sweep: see `tests/fill.rs`'s identical constant.
const LENGTHS: [usize; 4] = [0, 1, 999, 10_000];

// ----------------------------------------------------------------------------
// ParallelGenerate
// ----------------------------------------------------------------------------

/// Upstream's `generate_sync<T>(W, N, val)`, generalized over every
/// partitioner: every element of a freshly allocated `Vec<i64>` ends up
/// `val`, generated by a stateless closure.
fn parallel_generate<P>(workers: usize, make: impl Fn() -> P)
where
    P: SlicePartitioner + Send + 'static,
{
    let executor = Executor::new(workers);
    let mut taskflow = Taskflow::new();

    for n in LENGTHS {
        taskflow.clear();
        let mut part = Some(make());
        taskflow.emplace_runtime(move |runtime: &mut Runtime<'_>| {
            let part = part.take().expect("this task runs once");
            let mut data = vec![0i64; n];
            runtime.generate(&mut data, || 12, part);
            assert!(data.iter().all(|&v| v == 12), "n={n}");
        });
        executor.run(&taskflow).wait().expect("no task panicked");
    }
}

fn parallel_generate_static(workers: usize) {
    parallel_generate(workers, StaticPartitioner::<DefaultClosureWrapper>::default);
}

fn parallel_generate_dynamic(workers: usize) {
    parallel_generate(
        workers,
        DynamicPartitioner::<DefaultClosureWrapper>::default,
    );
}

fn parallel_generate_random(workers: usize) {
    parallel_generate(workers, RandomPartitioner::<DefaultClosureWrapper>::default);
}

fn parallel_generate_default(workers: usize) {
    parallel_generate(workers, DefaultPartitioner::default);
}

